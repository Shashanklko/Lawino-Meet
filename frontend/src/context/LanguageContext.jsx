const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    try {
      return localStorage.getItem('lawino_language') || 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (langId) => {
    setLanguageState(langId);
    try {
      localStorage.setItem('lawino_language', langId);
    } catch {}
  };

  const currentLanguage = LANGUAGES.find((l) => l.id === language) || LANGUAGES[0];

  const t = (key, fallback = '') => {
    if (!key) return '';
    const langDict = TRANSLATIONS[language] || TRANSLATIONS['en'];
    const enDict = TRANSLATIONS['en'] || {};

    // 1. Direct translation key match (e.g. 'landing.heroEyebrow')
    if (langDict && langDict[key]) {
      return langDict[key];
    }

    // 2. English text lookup (e.g. t('Overview') or t('Our Story'))
    if (language !== 'en') {
      const cleanKey = String(key).trim().toLowerCase();
      for (const [dictKey, enVal] of Object.entries(enDict)) {
        if (typeof enVal === 'string' && enVal.trim().toLowerCase() === cleanKey) {
          if (langDict[dictKey]) {
            return langDict[dictKey];
          }
        }
      }
    }

    // 3. Fallback to English dict key
    if (enDict[key]) {
      return enDict[key];
    }

    return fallback || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        currentLanguage,
        languages: LANGUAGES,
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
